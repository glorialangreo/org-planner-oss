test('backup file upload resets stale selections and shows concise errors', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Import', exact: true }).click();
  await page.getByRole('button', { name: 'Import Workspace', exact: true }).click();
  const input = page.getByLabel('Upload JSON backup');
  const preview = page.getByRole('button', { name: 'Preview import', exact: true });
  const payload = { name: 'planner.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backupFixture())) };
  await input.setInputFiles(payload);
  await expect(page.getByRole('status')).toContainText('planner.json is ready to preview');
  await expect(page.getByLabel('Backup JSON', { exact: true })).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Download roster template' })).toHaveCount(0);
  await expect(preview).toBeEnabled();
  await page.getByRole('button', { name: 'Import Roster', exact: true }).click();
  await page.getByRole('button', { name: 'Import Workspace', exact: true }).click();
  await expect(preview).toBeDisabled();
  expect(await input.evaluate((element: HTMLInputElement) => element.files?.length)).toBe(0);
  await input.setInputFiles(payload);
  await preview.click();
  await expect(page.getByRole('region', { name: 'Import preview' })).toContainText('Restore copies of 1 references, 1 scenarios and 1 snapshots.');
  await expect(page.getByRole('button', { name: 'Confirm restore copies' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('restore-preview.png'), fullPage: true });
  await page.getByRole('button', { name: 'Confirm restore copies' }).click();
  await expect(page.getByRole('heading', { name: 'Fictional plan' })).toBeVisible();
  await page.getByRole('button', { name: 'Import', exact: true }).click();
  await page.getByRole('button', { name: 'Import Workspace', exact: true }).click();
  await input.setInputFiles({ ...payload, buffer: Buffer.from('{"formatVersion":1,"baseline":{},"scenarios":[{}],"snapshots":[{}],"avatars":[{}]}') });
  await preview.click();
  const error = page.getByRole('alert');
  await expect(error).toContainText('Nothing has been restored');
  expect((await error.innerText()).length).toBeLessThan(400);
  await input.setInputFiles({ ...payload, buffer: Buffer.alloc(0) });
  await expect(error).toContainText('This file is empty');
  await expect(preview).toBeDisabled();
});
